export const TYPE_ALIASES: Record<string, string> = {
  'nav.simple': 'navbar.simple',
  'nav.centered': 'navbar.centered',
  'nav.cta': 'navbar.cta',
  'nav.transparent': 'navbar.transparent',
  'header.simple': 'navbar.simple',
  'header.centered': 'navbar.centered',
  'nav.generated': 'generated.nav',
  'footer.generated': 'generated.footer',
}

export function getBlock(type: string): BlockDefinition | undefined {
  return blockRegistry[type] ?? blockRegistry[TYPE_ALIASES[type]]
}

export function listBlocks(filter?: { category?: BlockCategory }): BlockDefinition[] {
  const all = Object.values(blockRegistry)
  if (!filter?.category) return all
  return all.filter((block) => block.category === filter.category)
}

export function blockTypes(): string[] {
  return Object.keys(blockRegistry)
}
